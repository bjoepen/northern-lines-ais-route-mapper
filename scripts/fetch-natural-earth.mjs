import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const BASE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson';
const OUT = join(process.cwd(), 'public', 'data', 'natural-earth');
const FILES = [
  'ne_10m_land.geojson',
  'ne_50m_land.geojson',
  'ne_110m_land.geojson',
];

await mkdir(OUT, { recursive: true });

for (const file of FILES) {
  const url = `${BASE}/${file}`;
  process.stdout.write(`Natural Earth: ${file} ... `);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  const text = await response.text();
  JSON.parse(text);
  await writeFile(join(OUT, file), text, 'utf8');
  console.log('ok');
}

await writeFile(join(OUT, 'SOURCE.md'), `# Natural Earth local cartography assets\n\nGenerated by \`npm run cartography:fetch-data\`.\n\nSource: https://github.com/nvkelso/natural-earth-vector\nDataset: Natural Earth Vector, public domain.\n\nFiles are intentionally fetched locally so the editorial renderer has no runtime dependency on a tile provider or third-party map service.\n`, 'utf8');
console.log(`Natural Earth assets ready in ${OUT}`);
